"""
`makemigrations(update = true)`: fold the model changes into the app's latest migration (which
must not be applied yet, nor depended on), optimized, instead of writing a new one.
"""
function update_migration(g::Graph, app, leaves; name, dry_run, questioner, log)
    length(leaves) == 1 || throw(MigrationError("makemigrations --update needs exactly one latest migration in '$app'"))
    k = only(leaves)
    m = g.nodes[k]
    k in applied_migrations() && throw(MigrationError("$(k[2]) has been applied; it can't be updated (write a new migration)"))
    any(o -> k in o.dependencies, values(g.nodes)) && throw(MigrationError("$(k[2]) is a dependency of another migration"))
    any(op -> op isa Union{RunJulia,RunSQL,SeparateDatabaseAndState}, m.operations) &&
        throw(MigrationError("$(k[2]) contains RunSQL, RunJulia or SeparateDatabaseAndState, which can't be rewritten"))
    new = detect_changes(g, app; questioner = questioner)
    if isempty(new)
        log("No changes detected" * (app == "project" ? "" : " in app '$app'"))
        return String[]
    end
    ops = optimize_operations(vcat(m.operations, new), state_before(g, k), app)
    um = Migration(; dependencies = m.dependencies, operations = ops, initial = m.initial, replaces = m.replaces)
    nm = something(name, k[2][6:end])
    path = write_file(app, parse(Int, k[2][1:4]), nm, um; dry_run = dry_run, log = log)
    !dry_run && path != m.path && rm(m.path)
    [path]
end

"""
    parse_number(name) -> Union{Int,Nothing}

A migration's number from its name, as Django's: a squashed one's is the last it replaces
("0002_squashed_0005" is 5), otherwise the leading digits, or nothing.
"""
function parse_number(name::AbstractString)
    m = match(r".*_squashed_(\d+)", name)
    m === nothing || return parse(Int, m[1])
    m = match(r"^\d+", name)
    m === nothing ? nothing : parse(Int, m.match)
end
next_number(g::Graph, app) = 1 + maximum([something(parse_number(k[2]), 0) for k in keys(g.nodes) if k[1] == app]; init = 0)

function write_file(app, number, name, m::Migration; dry_run = false, log = println)
    dir = migration_dir(app)
    dir === nothing && throw(MigrationError("app '$app' has no migrations directory; set MIGRATION_MODULES[\"$app\"]"))
    fname = lpad(number, 4, '0') * "_" * name * ".jl"
    path = joinpath(dir, fname)
    log("Migrations for '$app':")
    log("  $(relpath_or_abs(path))")
    for op in m.operations
        log("    - " * describe(op))
    end
    if !dry_run
        mkpath(dir)
        write(path, migration_code(m))
    end
    path
end
relpath_or_abs(p) = (r = relpath(p); startswith(r, "..") ? p : r)

"Apps whose last `makemigrations` left out foreign keys to tables of apps without migrations yet."
const DEFERRED_APPS = Ref(Set{String}())

"""
    makemigrations_apps(apps; kw...) -> paths

`makemigrations` for several apps: in dependency order, then once more for apps that had to
leave out foreign keys to another of the apps (a cycle), now that those apps have migrations.
"""
function makemigrations_apps(apps; dry_run = false, check = false, kw...)
    DEFERRED_APPS[] = Set{String}()
    order = app_order(apps)
    paths = reduce(vcat, [makemigrations(; app = a, dry_run = dry_run, check = check, kw...) for a in order]; init = String[])
    again = [a for a in order if a in DEFERRED_APPS[]]
    (dry_run || check || isempty(again)) && return paths
    DEFERRED_APPS[] = Set{String}()
    vcat(paths, reduce(vcat, [makemigrations(; app = a, kw...) for a in again]; init = String[]))
end

"""
    makemigrations(; app="project", name=nothing, empty=false, merge=false, dry_run=false,
                   check=false, questioner=ask, verbose=true) -> Vector{String}

Write a migration for the changes between `app`'s models and its migrations, and return
the paths written. `check=true` only reports whether a migration is needed (returns the
would-be paths without writing). `merge=true` writes a merge migration for conflicting
branches. `empty=true` writes a migration with no operations, for `RunSQL`/`RunJulia`.
"""
function makemigrations(; app = "project", name = nothing, empty = false, merge = false, dry_run = false,
                        check = false, update = false, questioner = ask, verbose = true)
    log(msg) = verbose && println(msg)
    app = string(app)
    g = build_graph(unique(vcat(migrated_apps(), [app])))
    leaves = leaf_nodes(g, app)
    update && return update_migration(g, app, leaves; name = name, dry_run = dry_run || check, questioner = questioner, log = log)
    if merge
        length(leaves) > 1 || (log("No conflicts detected to merge."); return String[])
        m = Migration(; dependencies = leaves)
        nm = something(name, "merge_" * join([k[2][1:4] for k in leaves], "_"))
        return [write_file(app, next_number(g, app), nm, m; dry_run = dry_run || check, log = log)]
    end
    check_conflicts(g)
    deferred = Tuple{String,String,String,String}[]
    ops = empty ? Operation[] : detect_changes(g, app; questioner = questioner, deferred = deferred)
    for (t, c, r, other) in deferred
        log("  Note: the foreign key $t.$c -> $r is left out until app '$other' has a migration creating $r; " *
            "makemigrations adds it then, in a migration that depends on '$other'.")
    end
    DEFERRED_APPS[] = isempty(deferred) ? DEFERRED_APPS[] : push!(DEFERRED_APPS[], app)
    if isempty(ops) && !empty
        log("No changes detected" * (app == "project" ? "" : " in app '$app'"))
        return String[]
    end
    initial = isempty(leaves)
    deps = Set{Tuple{String,String}}(leaves)
    tables = Dict(modelmeta(T).table => modelmeta(T).app for T in all_models())
    for op in ops, c in (op isa CreateModel ? op.columns : op isa Union{AddField,AlterField} ? [op.column] : Column[])
        c.references === nothing && continue
        # a FK to USER_MODEL depends on whichever app provides the user model
        c.references == "__user_model__" && (push!(deps, ("__user_model__", "__first__")); continue)
        other = get(tables, c.references, app)
        other == app && continue
        ol = leaf_nodes(g, other)
        isempty(ol) && (log("  Warning: $(c.references) belongs to app '$other', which has no migrations."); continue)
        union!(deps, ol)
    end
    # a renamed table: other apps' migrations name it by its old name, so they must run first (#252);
    # the rename depends on the latest migration of each app with a foreign key to it
    if any(op -> op isa RenameModel, ops)
        full = replay(g, keys(g.nodes))
        for op in ops
            op isa RenameModel || continue
            for t in values(full)
                (t.app == app || !any(c -> c.references == op.old, t.columns)) && continue
                union!(deps, leaf_nodes(g, t.app))
            end
        end
    end
    for op in ops
        if op isa AddField && !op.column.null && op.column.default === nothing
            bf = backfill_value(op.column)
            log(bf === nothing ?
                "  Warning: $(op.table).$(op.column.name) is NOT NULL with no default; existing rows have no value for it. Give the field a default or null=true." :
                "  Note: existing rows get $(repr(bf)) for the new NOT NULL column $(op.table).$(op.column.name).")
        end
    end
    m = Migration(; dependencies = sort(collect(deps)), operations = ops, initial = initial)
    if !initial && get(Juango.SETTINGS, :MIGRATION_LINT, :warn) !== false      # operations unsafe for a running site
        before = replay(g, reduce(union, (ancestors(g, l) for l in leaves); init = Set{Tuple{String,String}}()))
        m.app = app
        for w in lint_migration(m, before)
            log("  Warning ($(w.id)), operation $(w.op): $(w.msg)\n    $(w.hint)")
        end
    end
    [write_file(app, next_number(g, app), something(name, suggest_name(ops, initial)), m;
                dry_run = dry_run || check, log = log)]
end

"""
    optimize_operations(ops, before, app) -> Vector{Operation}

Fewer operations with the same effect: tables created along the way become one `CreateModel`
with their final definition (and vanish if they're deleted again). On other tables an
`AddField` absorbs later `AlterField`s and `RenameField`s of its column, an `AddField` followed
by a `RemoveField` cancels out, only the last of several `AlterField`s is kept (a `RenameField`
moves before it), renames of a column or a table in a row become one, an `AddIndex` or
`AddConstraint` that's removed again vanishes, and only the last `AlterUniqueTogether` or
`AlterModelTableComment` of a table is kept. `RunSQL`, `RunJulia` and `SeparateDatabaseAndState`
are barriers: nothing is moved or folded across them, so their code sees the tables as
they were at that point.
"""
function optimize_operations(ops::Vector{Operation}, before::SchemaState, app)
    state = copy_state(before)
    out = Operation[]
    seg = Operation[]
    flush!() = (append!(out, optimize_segment(seg, state, app)); empty!(seg))
    seg_start = copy_state(state)
    for op in ops
        if op isa Union{RunSQL,RunJulia,SeparateDatabaseAndState}
            flush!()
            state_forwards!(op, state, app)
            push!(out, op)
            seg_start = copy_state(state)
            continue
        end
        # a table created again under a name the segment started with (deleted or renamed away
        # first): the creates move to the front of a segment, so start a new one
        if op isa CreateModel && haskey(seg_start, op.table)
            flush!()
            seg_start = copy_state(state)
        end
        push!(seg, op)
    end
    flush!()
    out
end

"One stretch of operations without barriers, optimized; `state` moves on past them."
function optimize_segment(ops::Vector{Operation}, state::SchemaState, app)
    isempty(ops) && return Operation[]
    after = copy_state(state)
    created = Set{String}()            # tables created by these operations, by their current name
    kept = Operation[]
    for op in ops
        state_forwards!(op, after, app)
        if op isa CreateModel
            push!(created, op.table)
        elseif op isa RenameModel && op.old in created
            delete!(created, op.old); push!(created, op.new)
        elseif op isa DeleteModel && op.table in created
            delete!(created, op.table)
        elseif hasfield(typeof(op), :table) && getfield(op, :table) in created
            # folded into the table's CreateModel
        else
            push!(kept, op)
        end
    end
    creates = Operation[CreateModel(t.name; model = t.model, columns = t.columns, unique_together = t.unique_together,
                                    parent = t.parent, pk = t.pk, indexes = t.indexes, constraints = t.constraints,
                                    pk_columns = t.pk_columns, comment = t.comment)
                        for t in creation_order(Table[after[n] for n in created])]
    for (k, v) in after                # (the caller's state, moved past the segment)
        state[k] = v
    end
    for k in collect(keys(state))
        haskey(after, k) || delete!(state, k)
    end
    vcat(creates, reduce_field_ops(kept))
end

"The table an operation works on (a RenameModel: its new name), or nothing."
op_table(op) = op isa RenameModel ? op.new : hasfield(typeof(op), :table) ? getfield(op, :table) : nothing
op_tables(op) = op isa RenameModel ? (op.old, op.new) : (op_table(op),)

"Merge operations on the same column, index, constraint or table (barriers are handled by the caller)."
function reduce_field_ops(ops::Vector{Operation})
    out = Operation[]
    col(op) = op isa Union{AddField,AlterField} ? (op.table, op.column.name) : op isa RemoveField ? (op.table, op.name) : nothing
    # nothing after out[i] works on `table`
    untouched_after(i, table) = !any(x -> table in op_tables(x), @view out[i+1:end])
    for op in ops
        if op isa RenameField
            i = findlast(x -> x isa Union{AddField,AlterField,RenameField} && x.table == op.table &&
                              (x isa RenameField ? x.new : x.column.name) == op.old, out)
            if i !== nothing && untouched_after(i, op.table)
                prev = out[i]
                if prev isa AddField                                   # added under the new name
                    out[i] = AddField(prev.table, Juango.with_column(prev.column; name = op.new)); continue
                elseif prev isa RenameField                            # renamed in one go (or back)
                    prev.old == op.new ? deleteat!(out, i) : (out[i] = RenameField(op.table, prev.old, op.new)); continue
                else                                                   # the rename moves before the AlterField
                    deleteat!(out, i)
                    r = i - 1           # (and joins a rename just before it)
                    if r >= 1 && out[r] isa RenameField && out[r].table == op.table && out[r].new == op.old
                        out[r].old == op.new ? deleteat!(out, r) : (out[r] = RenameField(op.table, out[r].old, op.new))
                    else
                        insert!(out, i, RenameField(op.table, op.old, op.new))
                    end
                    push!(out, AlterField(prev.table, Juango.with_column(prev.column; name = op.new))); continue
                end
            end
        elseif op isa RenameModel
            i = findlast(x -> x isa RenameModel && x.new == op.old, out)
            if i !== nothing && untouched_after(i, op.old)
                prev = out[i]
                prev.old == op.new ? deleteat!(out, i) : (out[i] = RenameModel(prev.old, op.new; model = something(op.model, prev.model, Some(nothing))))
                continue
            end
        elseif op isa Union{RemoveIndex,RemoveConstraint}
            add = op isa RemoveIndex ? AddIndex : AddConstraint
            i = findlast(x -> x isa add && x.table == op.table && (x isa AddIndex ? x.index.name : x.constraint.name) == op.name, out)
            if i !== nothing
                deleteat!(out, i); continue
            end
        elseif op isa Union{AlterUniqueTogether,AlterModelTableComment}
            i = findlast(x -> x isa typeof(op) && x.table == op.table, out)
            i === nothing || deleteat!(out, i)
        end
        c = col(op)
        # an earlier op on the same column, with nothing that renames columns of that table in between
        i = c === nothing ? nothing : findlast(x -> col(x) == c, out)
        if i !== nothing && !any(x -> x isa RenameField && x.table == c[1], out[i+1:end])
            prev = out[i]
            if prev isa AddField && op isa AlterField
                out[i] = AddField(prev.table, op.column); continue
            elseif prev isa AddField && op isa RemoveField
                deleteat!(out, i); continue
            elseif prev isa AlterField && op isa Union{AlterField,RemoveField}
                deleteat!(out, i)
            end
        end
        push!(out, op)
    end
    out
end

"""
    optimizemigration(app, name; check = false) -> Bool

Rewrite one migration with fewer operations (see `optimize_operations`), keeping its name and
dependencies. Returns whether it changed; `check = true` only reports it. Migrations with
`RunSQL`, `RunJulia` or `SeparateDatabaseAndState` are left alone (their code can't be rewritten).
"""
function optimizemigration(app, name; check = false, verbose = true)
    log(msg) = verbose && println(msg)
    app = string(app)
    g = build_graph(; applied = Set{Tuple{String,String}}())
    k = resolve_name(g, app, string(name))
    m = g.nodes[k]
    any(op -> op isa Union{RunJulia,RunSQL,SeparateDatabaseAndState}, m.operations) &&
        throw(MigrationError("$(k[2]) contains RunSQL, RunJulia or SeparateDatabaseAndState, which optimizemigration can't rewrite"))
    ops = optimize_operations(m.operations, state_before(g, k), app)
    if length(ops) == length(m.operations) && all(((a, b),) -> typeof(a) === typeof(b), zip(ops, m.operations))
        log("No optimizations possible.")
        return false
    end
    log("Optimized from $(length(m.operations)) operations to $(length(ops)) operations.")
    check && return true
    write(m.path, migration_code(Migration(; dependencies = m.dependencies, operations = ops, initial = m.initial, replaces = m.replaces)))
    log("  " * relpath_or_abs(m.path))
    true
end

"""
    squashmigrations(app, stop; start = nothing, name = nothing, dry_run = false) -> path

Write one migration that stands for `app`'s migrations from `start` (default: the first) to
`stop`. Operations on tables that existed before are kept as they were; tables created in
the range become one `CreateModel` with their final definition. The new file lists the
migrations it `replaces`: databases that applied all (or none) of them use it, others keep
using the originals. Once every database has migrated past it, delete the old files and
the `replaces` line. Ranges with `RunSQL` or `RunJulia` (data migrations) are refused.
"""
function squashmigrations(app, stop; start = nothing, name = nothing, dry_run = false, verbose = true)
    log(msg) = verbose && println(msg)
    app = string(app)
    g = build_graph(; applied = Set{Tuple{String,String}}())
    order = [k for k in topo_order(g) if k[1] == app]
    isempty(order) && throw(MigrationError("app '$app' has no migrations"))
    last_k = resolve_name(g, app, string(stop))
    first_k = start === nothing ? order[1] : resolve_name(g, app, string(start))
    i, j = findfirst(==(first_k), order), findfirst(==(last_k), order)
    (i !== nothing && j !== nothing && j > i) || throw(MigrationError("squashmigrations needs at least two migrations, from $(first_k[2]) to $(last_k[2])"))
    range = order[i:j]
    for k in range
        isempty(g.nodes[k].replaces) || throw(MigrationError("$(k[2]) is itself a squashed migration; squash the originals instead"))
        for op in g.nodes[k].operations
            op isa Union{RunSQL,RunJulia,SeparateDatabaseAndState} && throw(MigrationError(
                "$(k[2]) has a $(nameof(typeof(op))) operation; squashmigrations only combines schema changes " *
                "(squash the migrations before and after it separately)"))
        end
    end
    inrange = Set(range)
    deps = sort(unique([d for k in range for d in g.nodes[k].dependencies if !(d in inrange)]))
    ops = optimize_operations(Operation[op for k in range for op in g.nodes[k].operations], state_before(g, first_k), app)
    m = Migration(; dependencies = deps, operations = ops, initial = g.nodes[first_k].initial, replaces = range)
    number = parse(Int, first_k[2][1:4])
    write_file(app, number, something(name, "squashed_" * last_k[2]), m; dry_run = dry_run, log = log)
end
