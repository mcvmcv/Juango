# System images: manage.jl build ---------------------------------------------------------------------------
#
#     julia --project manage.jl build                  # build/juango.so (or .dylib / .dll)
#     julia --project -J build/juango.so manage.jl runserver 0.0.0.0:8000
#
# A freshly started Julia compiles code the first time it runs, so the first requests to a new
# server are slow. `build` makes a system image (PackageCompiler.jl) of the project's packages,
# compiled while running a workload taken from the project itself: every URL without parameters is
# requested with the test client (against an in-memory SQLite copy of the schema), every template
# is parsed, and with `workload = :tests` the project's tests run too. PackageCompiler is installed
# into a shared environment (`@juango-build`) the first time, so it isn't a dependency of the project.

const BUILD_ENV = "@juango-build"
# The image is compiled in one process that loads every package from source (PackageCompiler builds
# with --pkgimages=no): the example blog peaked at 12 GB. A heap-size hint makes its collector work
# harder: 10.9 GB, and faster too (8.6 minutes, not 11).
const BUILD_ARGS = "`--heap-size-hint=3G`"
sysimage_ext() = Sys.iswindows() ? "dll" : Sys.isapple() ? "dylib" : "so"

"Template names (relative paths) under the template directories, for the build workload."
function template_names(dirs = template_dirs())
    names = String[]
    for d in dirs, (root, _, files) in walkdir(d), f in files
        any(endswith(f, e) for e in (".html", ".txt", ".xml", ".json", ".css", ".js")) && push!(names, relpath(joinpath(root, f), d))
    end
    unique!(names)
end

"""
    build_workload(project_file; tests = false) -> String

The code `build` runs while compiling the system image: load the project, make an in-memory
database with its schema, request each parameterless URL and parse each template.
"""
function build_workload(project_file::AbstractString; tests::Bool = false, test_file = nothing)
    tf = tests ? something(test_file, joinpath(dirname(project_file), "test", "runtests.jl")) : nothing
    """
    # Generated by `manage.jl build` (Juango $VERSION_STRING): run while the system image is compiled.
    include($(repr(abspath(project_file))))
    using Juango
    let
        Juango.configure!(DATABASE = ":memory:", DEBUG = false, ALLOWED_HOSTS = ["*"])
        redirect_stdout(devnull) do
            try Juango.migrate(verbose = false) catch e; @warn "build workload: migrate failed" exception = e end
        end
        c = Juango.Testing.Client()
        for (route, name, view) in Juango.all_routes()
            occursin('<', route) && continue                   # needs parameters
            try get(c, "/" * route) catch end
        end
        for t in Juango.template_names()
            try Juango.get_template(t) catch end
        end
    end
    $(tf === nothing ? "" : "try include($(repr(abspath(tf)))) catch e; @warn \"build workload: the tests failed\" exception = e end")
    """
end

# --- standalone apps: manage.jl build --app ---
#
#     julia --project manage.jl build --app                 # build/app: bin/<name>, the libraries, the project
#     build/app/bin/blog runserver 0.0.0.0:8000             # on a machine without Julia
#
# PackageCompiler's create_app needs a package with a julia_main, and a project made by startproject
# is a script, so build writes a small wrapper package (build/app_src) with the project's
# dependencies and Manifest. Its julia_main does what manage.jl does: include project.jl (copied
# into the app, at app/project, or JUANGO_PROJECT_DIR) and run the command line. The system image
# inside is compiled with the same workload as `build`'s.

"A package name from the project's directory: `blog` -> `BlogApp`."
app_package_name(proj_dir) = (b = replace(titlecase(replace(basename(normpath(proj_dir)), r"[^A-Za-z0-9]+" => " ")), " " => "");
                              (isempty(b) || isdigit(b[1]) ? "Juango" * b : b) * "App")

"A Manifest's or Project's relative `path`s (dev'ed packages, [sources]) made absolute, from `dir`."
function absolute_paths!(d, dir)
    for (k, v) in d
        if v isa AbstractDict
            absolute_paths!(v, dir)
        elseif v isa AbstractVector
            foreach(x -> x isa AbstractDict && absolute_paths!(x, dir), v)
        elseif k == "path" && v isa AbstractString && !isabspath(v)
            d[k] = normpath(joinpath(dir, v))
        end
    end
    d
end

"""
    write_app_package(proj_dir, src_dir) -> package name

The wrapper package `create_app` builds: the project's dependencies (and Manifest, so the
versions are the project's), and a `julia_main` that runs the bundled project's command line.
"""
function write_app_package(proj_dir::AbstractString, src_dir::AbstractString)
    name = app_package_name(proj_dir)
    rm(src_dir; force = true, recursive = true)
    mkpath(joinpath(src_dir, "src"))
    proj = TOML.parsefile(joinpath(proj_dir, "Project.toml"))
    deps = get(proj, "deps", Dict{String,Any}())
    haskey(deps, "Juango") || throw(ArgumentError("build --app: the project's Project.toml has no Juango dependency"))
    p = Dict{String,Any}("name" => name, "uuid" => string(uuid5(UUID("05cba04f-b8df-4159-83db-d292e8d0197f"), abspath(proj_dir))),
                         "version" => "0.1.0", "deps" => deps)
    haskey(proj, "sources") && (p["sources"] = absolute_paths!(deepcopy(proj["sources"]), proj_dir))
    haskey(proj, "compat") && (p["compat"] = proj["compat"])
    open(io -> TOML.print(io, p), joinpath(src_dir, "Project.toml"), "w")
    mf = joinpath(proj_dir, "Manifest.toml")
    if isfile(mf)
        m = absolute_paths!(TOML.parsefile(mf), proj_dir)
        open(io -> TOML.print(io, m), joinpath(src_dir, "Manifest.toml"), "w")
    end
    write(joinpath(src_dir, "src", name * ".jl"), """
    # Generated by `manage.jl build --app` (Juango $VERSION_STRING).
    module $name
    using Juango

    "The project's directory: JUANGO_PROJECT_DIR, else the app's own copy (app/project)."
    project_dir() = get(ENV, "JUANGO_PROJECT_DIR", normpath(joinpath(Sys.BINDIR, "..", "project")))

    function julia_main()::Cint
        try
            dir = project_dir()
            isfile(joinpath(dir, "project.jl")) || (println(stderr, "no project.jl in ", dir, " (set JUANGO_PROJECT_DIR)"); return 1)
            Base.include(Main, joinpath(dir, "project.jl"))
            Base.invokelatest(Juango.execute_from_command_line, ARGS)
        catch e
            e isa InterruptException && return 0
            Base.invokelatest(Base.display_error, e, catch_backtrace())
            return 1
        end
        return 0
    end
    end
    """)
    name
end

"Copy the project's files into the app (not build/, .git, databases or logs)."
function copy_project_into(proj_dir, dest)
    skip(rel) = any(startswith(rel, x) for x in ("build", ".git", "__pycache__")) || any(endswith(rel, x) for x in (".sqlite3", ".log", ".db"))
    for (root, _, files) in walkdir(proj_dir), f in files
        src = joinpath(root, f)
        rel = relpath(src, proj_dir)
        skip(rel) && continue
        mkpath(dirname(joinpath(dest, rel)))
        cp(src, joinpath(dest, rel); force = true)
    end
end

"Make sure PackageCompiler is installed in the shared build environment."
function ensure_package_compiler(julia = Base.julia_cmd(); log = println)
    ok = success(pipeline(`$julia --project=$BUILD_ENV -e "import PackageCompiler"`; stderr = devnull, stdout = devnull))
    ok && return true
    log("Installing PackageCompiler into $BUILD_ENV (once)...")
    run(`$julia --project=$BUILD_ENV -e "import Pkg; Pkg.add(\"PackageCompiler\")"`)
    true
end

"""
    build(; output = "build/juango.<ext>", workload = :urls, project_file = "project.jl",
          packages = nothing, dry_run = false) -> path or command

Build a system image for the project (see the top of this file). `workload` is `:urls`, `:tests`
(the URLs and the project's tests) or `:none`. `packages` defaults to the project's `[deps]`.
`dry_run = true` writes the workload and returns the command without running it. `app = true`
builds a standalone app instead (`build_app`). `cpu_target` is passed to PackageCompiler: by
default an image is compiled for this machine's CPU and an app for several CPU types, so it runs
on other machines; `cpu_target = "native"` compiles an app for this CPU only, which needs less
memory and time to build.
"""
function build(; output = nothing, workload = :urls, project_file = nothing, packages = nothing,
               dry_run::Bool = false, app::Bool = false, cpu_target = nothing, julia = Base.julia_cmd(), log = println)
    proj_dir = dirname(something(Base.active_project(), joinpath(pwd(), "Project.toml")))
    pf = abspath(something(project_file, joinpath(proj_dir, "project.jl")))
    isfile(pf) || throw(ArgumentError("build: no project file at $pf (pass project_file)"))
    out = abspath(something(output, joinpath(proj_dir, "build", app ? "app" : "juango." * sysimage_ext())))
    mkpath(dirname(out))
    wl = Symbol(workload)
    cpu = cpu_target === nothing ? "" : ", cpu_target = $(repr(string(cpu_target)))"
    app && return build_app(proj_dir, pf, out, wl; dry_run, julia, log, cpu)
    wl in (:urls, :tests, :none) || throw(ArgumentError("build: workload must be :urls, :tests or :none"))
    wfile = joinpath(dirname(out), "precompile_workload.jl")
    write(wfile, wl === :none ? "using Juango\n" : build_workload(pf; tests = wl === :tests))
    pkgs = packages !== nothing ? String[string(p) for p in packages] :
           (projfile = joinpath(proj_dir, "Project.toml"); isfile(projfile) ?
            sort(collect(keys(get(TOML.parsefile(projfile), "deps", Dict())))) : ["Juango"])
    script = "using PackageCompiler; create_sysimage($(repr(pkgs)); sysimage_path = $(repr(out)), " *
             "precompile_execution_file = $(repr(wfile)), project = $(repr(proj_dir)), sysimage_build_args = $BUILD_ARGS$cpu)"
    cmd = addenv(`$julia --project=$proj_dir -e $script`, "JULIA_LOAD_PATH" => "@:$BUILD_ENV:@stdlib")
    dry_run && return cmd
    ensure_package_compiler(julia; log = log)
    log("Building $out (this takes about ten minutes and needs about 11 GB of free memory)...")
    run(cmd)
    log("Done. Start with: julia --project -J $(relpath(out, proj_dir)) manage.jl runserver")
    out
end

"`build(; app = true)`: a standalone app (see `write_app_package`)."
function build_app(proj_dir, pf, out, wl; dry_run = false, julia = Base.julia_cmd(), log = println, cpu = "")
    src = joinpath(dirname(out), "app_src")
    name = write_app_package(proj_dir, src)
    wfile = joinpath(dirname(out), "precompile_workload.jl")
    write(wfile, wl === :none ? "using Juango\n" : build_workload(pf; tests = wl === :tests))
    exe = lowercase(replace(basename(normpath(proj_dir)), r"[^A-Za-z0-9_-]+" => "_"))
    script = "using PackageCompiler; create_app($(repr(src)), $(repr(out)); executables = [$(repr(exe)) => \"julia_main\"], " *
             "precompile_execution_file = $(repr(wfile)), force = true, include_lazy_artifacts = true, sysimage_build_args = $BUILD_ARGS$cpu)"
    cmd = addenv(`$julia --project=$src -e $script`, "JULIA_LOAD_PATH" => "@:$BUILD_ENV:@stdlib")
    dry_run && return cmd
    ensure_package_compiler(julia; log = log)
    run(addenv(`$julia --project=$src -e "import Pkg; Pkg.instantiate()"`, "JULIA_LOAD_PATH" => "@:@stdlib"))
    log("Building the app $out (this takes about ten minutes and needs about 11 GB of free memory)...")
    run(cmd)
    copy_project_into(proj_dir, joinpath(out, "project"))
    log("Done. Run it with: $(relpath(joinpath(out, "bin", exe), proj_dir)) runserver 0.0.0.0:8000 (no Julia needed)")
    out
end
