# System images: manage.jl build ---------------------------------------------------------------------------
#
#     julia --project manage.jl build                  # build/juango.so (or .dylib / .dll)
#     julia --project -J build/juango.so manage.jl runserver 0.0.0.0:8000
#
# A freshly started Julia compiles code the first time it runs, so the first requests to a new
# server are slow. `build` makes a system image (PackageCompiler.jl) of the project's packages,
# compiled while running a workload taken from the project itself: every URL without parameters is
# requested with the test client (against an in-memory SQLite copy of the schema), every template
# is parsed, and with `workload = :tests` the project's tests run too. PackageCompiler is installed
# into a shared environment (`@juango-build`) the first time, so it isn't a dependency of the project.

const BUILD_ENV = "@juango-build"
sysimage_ext() = Sys.iswindows() ? "dll" : Sys.isapple() ? "dylib" : "so"

"Template names (relative paths) under the template directories, for the build workload."
function template_names(dirs = template_dirs())
    names = String[]
    for d in dirs, (root, _, files) in walkdir(d), f in files
        any(endswith(f, e) for e in (".html", ".txt", ".xml", ".json", ".css", ".js")) && push!(names, relpath(joinpath(root, f), d))
    end
    unique!(names)
end

"""
    build_workload(project_file; tests = false) -> String

The code `build` runs while compiling the system image: load the project, make an in-memory
database with its schema, request each parameterless URL and parse each template.
"""
function build_workload(project_file::AbstractString; tests::Bool = false, test_file = nothing)
    tf = tests ? something(test_file, joinpath(dirname(project_file), "test", "runtests.jl")) : nothing
    """
    # Generated by `manage.jl build` (Juango $VERSION_STRING): run while the system image is compiled.
    include($(repr(abspath(project_file))))
    using Juango
    let
        Juango.configure!(DATABASE = ":memory:", DEBUG = false, ALLOWED_HOSTS = ["*"])
        redirect_stdout(devnull) do
            try Juango.migrate(verbose = false) catch e; @warn "build workload: migrate failed" exception = e end
        end
        c = Juango.Testing.Client()
        for (route, name, view) in Juango.all_routes()
            occursin('<', route) && continue                   # needs parameters
            try get(c, "/" * route) catch end
        end
        for t in Juango.template_names()
            try Juango.get_template(t) catch end
        end
    end
    $(tf === nothing ? "" : "try include($(repr(abspath(tf)))) catch e; @warn \"build workload: the tests failed\" exception = e end")
    """
end

"Make sure PackageCompiler is installed in the shared build environment."
function ensure_package_compiler(julia = Base.julia_cmd(); log = println)
    ok = success(pipeline(`$julia --project=$BUILD_ENV -e "import PackageCompiler"`; stderr = devnull, stdout = devnull))
    ok && return true
    log("Installing PackageCompiler into $BUILD_ENV (once)...")
    run(`$julia --project=$BUILD_ENV -e "import Pkg; Pkg.add(\"PackageCompiler\")"`)
    true
end

"""
    build(; output = "build/juango.<ext>", workload = :urls, project_file = "project.jl",
          packages = nothing, dry_run = false) -> path or command

Build a system image for the project (see the top of this file). `workload` is `:urls`, `:tests`
(the URLs and the project's tests) or `:none`. `packages` defaults to the project's `[deps]`.
`dry_run = true` writes the workload and returns the command without running it.
"""
function build(; output = nothing, workload = :urls, project_file = nothing, packages = nothing,
               dry_run::Bool = false, julia = Base.julia_cmd(), log = println)
    proj_dir = dirname(something(Base.active_project(), joinpath(pwd(), "Project.toml")))
    pf = abspath(something(project_file, joinpath(proj_dir, "project.jl")))
    isfile(pf) || throw(ArgumentError("build: no project file at $pf (pass project_file)"))
    out = abspath(something(output, joinpath(proj_dir, "build", "juango." * sysimage_ext())))
    mkpath(dirname(out))
    wl = Symbol(workload)
    wl in (:urls, :tests, :none) || throw(ArgumentError("build: workload must be :urls, :tests or :none"))
    wfile = joinpath(dirname(out), "precompile_workload.jl")
    write(wfile, wl === :none ? "using Juango\n" : build_workload(pf; tests = wl === :tests))
    pkgs = packages !== nothing ? String[string(p) for p in packages] :
           (projfile = joinpath(proj_dir, "Project.toml"); isfile(projfile) ?
            sort(collect(keys(get(TOML.parsefile(projfile), "deps", Dict())))) : ["Juango"])
    script = "using PackageCompiler; create_sysimage($(repr(pkgs)); sysimage_path = $(repr(out)), " *
             "precompile_execution_file = $(repr(wfile)), project = $(repr(proj_dir)))"
    cmd = addenv(`$julia --project=$proj_dir -e $script`, "JULIA_LOAD_PATH" => "@:$BUILD_ENV:@stdlib")
    dry_run && return cmd
    ensure_package_compiler(julia; log = log)
    log("Building $out (this takes several minutes and a few GB of memory)...")
    run(cmd)
    log("Done. Start with: julia --project -J $(relpath(out, proj_dir)) manage.jl runserver")
    out
end
